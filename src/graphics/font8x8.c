const uint32_t font8x8_block_count = sizeof(font8x8_blocks) / sizeof(font8x8_block_t);

// Utility functions implementation
const char* font8x8_get_glyph(uint32_t codepoint) {
    for (uint32_t i = 0; i < font8x8_block_count; i++) {
        const font8x8_block_t* block = &font8x8_blocks[i];
        if (codepoint >= block->unicode_start && codepoint <= block->unicode_end) {
            uint32_t index = codepoint - block->unicode_start;
            if (index < block->count) {
                return block->data[index];
            }
        }
    }
    // Return space character as fallback
    return font8x8_basic[0x20];
}

bool font8x8_is_supported(uint32_t codepoint) {
    for (uint32_t i = 0; i < font8x8_block_count; i++) {
        const font8x8_block_t* block = &font8x8_blocks[i];
        if (codepoint >= block->unicode_start && codepoint <= block->unicode_end) {
            uint32_t index = codepoint - block->unicode_start;
            return index < block->count;
        }
    }
    return false;
}

uint32_t font8x8_get_block_count(void) {
    return font8x8_block_count;
}

const font8x8_block_t* font8x8_get_block_info(uint32_t index) {
    if (index >= font8x8_block_count) {
        return NULL;
    }
    return &font8x8_blocks[index];
}

// Render a single 8x8 character to a buffer
void font8x8_render_char(const char glyph[8], uint8_t* buffer,
                        uint32_t buffer_width, uint32_t x, uint32_t y,
                        uint32_t fg_color, uint32_t bg_color) {
    if (!glyph || !buffer) {
        return;
    }

    for (int dy = 0; dy < 8; dy++) {
        for (int dx = 0; dx < 8; dx++) {
            uint32_t pixel_x = x + dx;
            uint32_t pixel_y = y + dy;

            if (pixel_x < buffer_width) {
                uint8_t pixel = (glyph[dy] & (0x80 >> dx)) ? fg_color : bg_color;
                uint32_t offset = (pixel_y * buffer_width + pixel_x);
                buffer[offset] = pixel;
            }
        }
    }
}

// Render a string using 8x8 font
void font8x8_render_string(const char* str, uint8_t* buffer,
                          uint32_t buffer_width, uint32_t buffer_height,
                          uint32_t x, uint32_t y,
                          uint32_t fg_color, uint32_t bg_color) {
    if (!str || !buffer) {
        return;
    }

    uint32_t current_x = x;
    uint32_t current_y = y;

    while (*str && current_y + 8 <= buffer_height) {
        if (*str == '\n') {
            current_x = x;
            current_y += 8;
            str++;
            continue;
        }

        if (current_x + 8 > buffer_width) {
            current_x = x;
            current_y += 8;
            if (current_y + 8 > buffer_height) {
                break;
            }
        }

        const char* glyph = font8x8_get_glyph((unsigned char)*str);
        font8x8_render_char(glyph, buffer, buffer_width,
                           current_x, current_y, fg_color, bg_color);

        current_x += 8;
        str++;
    }
}
